#!/usr/bin/env node
/**
 * Re-asserts the library's own spacing above the theme's universal reset.
 *
 * The library ships inside `@layer skeletonic`, deliberately: per
 * wrap-cascade-layers.mjs, "any consumer styles outside any layer beat the
 * skeletonic layer — this is the desired property". The showcase's vendored
 * theme then opens with an unlayered
 *
 *     *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0 }
 *
 * and an unlayered declaration beats every layer. The result was that the
 * library's spacing was absent from the entire site: `select`, `input`,
 * `textarea`, `.badge` and `.command-item` all computed `padding: 0`, which is
 * why the select's label sat flush against its border. The only components that
 * looked right were the ones the theme happens to style itself, like `.card`.
 *
 * A blanket reset is the one thing a page showcasing a component library must
 * not do, but the theme is vendored byte-for-byte so it can be re-pulled. This
 * script instead lifts every spacing declaration out of the compiled library
 * CSS and re-emits it unlayered, where it outranks the reset again.
 *
 * Selectors the theme styles itself are skipped. The theme owns its own look
 * for those — `.card` is the theme's card on this site, with the theme's
 * padding — and restoring the library's value there would be a redesign rather
 * than a repair.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Same order the page links them in: a later bundle must keep overriding an
// earlier one here exactly as it does inside the layer.
const SOURCES = [
  "dist/css/core/skeletonic.css",
  "dist/css/core/skeletonic-ui.css",
];
const THEME = join(root, "_layouts/styles.css");
const OUT = join(root, "_layouts/library-spacing.css");

const SPACING = /^(padding|margin|gap|row-gap|column-gap)(-(top|right|bottom|left|inline|block))?(-(start|end))?$/;

/** Splits a stylesheet into top-level rules, descending into at-rule blocks. */
function* rules(css, prelude = []) {
  let i = 0;
  while (i < css.length) {
    const brace = css.indexOf("{", i);
    if (brace === -1) return;
    let selector = css.slice(i, brace).trim();
    // Skip statement at-rules such as `@layer a, b;` and `@charset`.
    const semi = selector.lastIndexOf(";");
    if (semi !== -1) selector = selector.slice(semi + 1).trim();

    let depth = 1, j = brace + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === "{") depth += 1;
      else if (css[j] === "}") depth -= 1;
      j += 1;
    }
    const body = css.slice(brace + 1, j - 1);

    if (selector.startsWith("@")) {
      // `@layer skeletonic { … }` contributes no condition of its own; a
      // `@media`/`@supports` condition has to be carried through.
      const carry = /^@layer\b/.test(selector) ? prelude : [...prelude, selector];
      yield* rules(body, carry);
    } else if (selector) {
      yield { selector, body, prelude };
    }
    i = j;
  }
}

const themeCss = existsSync(THEME) ? readFileSync(THEME, "utf8") : "";
const themeSelectors = new Set();
for (const { selector } of rules(themeCss)) {
  for (const part of selector.split(",")) themeSelectors.add(part.trim());
}

const blocks = new Map(); // condition -> [css strings]
let kept = 0;

for (const rel of SOURCES) {
  const path = join(root, rel);
  if (!existsSync(path)) {
    console.error(`emit-library-spacing: missing ${rel}; run the library build first.`);
    process.exit(1);
  }
  for (const { selector, body, prelude } of rules(readFileSync(path, "utf8"))) {
    const spacing = body
      .split(";")
      .map(d => d.trim())
      .filter(d => {
        const name = d.slice(0, d.indexOf(":")).trim().toLowerCase();
        return SPACING.test(name);
      });
    if (spacing.length === 0) continue;

    // The theme owns anything it styles itself.
    const parts = selector.split(",").map(s => s.trim()).filter(s => !themeSelectors.has(s));
    if (parts.length === 0) continue;

    const condition = prelude.join(" && ");
    if (!blocks.has(condition)) blocks.set(condition, []);
    blocks.get(condition).push(`${parts.join(",")}{${spacing.join(";")}}`);
    kept += 1;
  }
}

const header = `/* Generated by scripts/emit-library-spacing.mjs — do not edit.
 *
 * The library's spacing, re-emitted outside @layer so it outranks the theme's
 * unlayered universal reset. See the script for why this exists.
 */\n`;

const out = [header];
for (const [condition, css] of blocks) {
  if (!condition) { out.push(css.join("\n")); continue; }
  const opens = condition.split(" && ");
  out.push(`${opens.join("{")}{${css.join("\n")}${"}".repeat(opens.length)}`);
}

writeFileSync(OUT, out.join("\n") + "\n", "utf8");
console.log(`emit-library-spacing: re-asserted ${kept} spacing rule(s) above the theme reset.`);
